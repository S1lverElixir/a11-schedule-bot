ANCHOR_MONDAY = date(2026, 9, 21)


def week_mark(day: date) -> str:
    """Черта недели («над» или «под»), содержащей день day."""
    monday = day - timedelta(days=day.weekday())
    weeks = (monday - ANCHOR_MONDAY).days // 7
    return "под" if weeks % 2 == 0 else "над"


